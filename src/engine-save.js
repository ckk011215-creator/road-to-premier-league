/* ================= 存檔版本與舊存檔轉換 ================= */
/* SAVE_VER：存檔格式版本。每次改動存檔結構便加一，並在 MIGRATIONS 加入由上一版轉換的步驟。
   舊存檔讀取時會由原本的版本逐步轉換到最新版本。 */
const SAVE_VER = 2;
const MIGRATIONS = {
  /* v1（0.4.0 或以前）→ v2（0.5.0）：補上後來加入的欄位 */
  2: S => {
    S.m = S.m || {}; if(S.m.mates==null) S.m.mates = 50; if(S.m.fans==null) S.m.fans = 20;
    ['flags','life','ach','fam','gain','tmp'].forEach(k => { if(!S[k] || typeof S[k]!=='object') S[k] = {}; });
    ['recent','flog','honours','log','hist','cohort','seen'].forEach(k => { if(!Array.isArray(S[k])) S[k] = []; });
    if(S.money==null) S.money = 0; if(S.earn==null) S.earn = 0; if(S.caps==null) S.caps = 0;
    if(S.flags.agentSigned && !S.agent) S.agent = { type:'indie', rel:60 };
    if(S.pro && S.pro.trust==null) S.pro.trust = 50;
  }
};
/* 回傳 { ok, from, msg } */
function migrateS(S){
  if(!S || typeof S!=='object' || !S.seed) return { ok:false, msg:'存檔內容不完整。' };
  const from = S.v || 1;
  if(from > SAVE_VER) return { ok:false, msg:`這個存檔來自較新版本的遊戲（${S.ver||'未知版本'}），請先更新遊戲。` };
  for(let v = from+1; v <= SAVE_VER; v++){ if(MIGRATIONS[v]) MIGRATIONS[v](S); S.v = v; }
  S.ver = GAME_VER;
  return { ok:true, from };
}

